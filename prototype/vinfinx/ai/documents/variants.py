"""The document variants (MACRO_DOCUMENT_SPEC.md, "Variants"). Each changes one thing relative to the clean base
document with the same seed and records what it changed and what the pipeline should conclude."""
from __future__ import annotations

from dataclasses import dataclass, replace
from datetime import datetime
from decimal import Decimal
from typing import Any

from ..catalog import Catalogue
from ..schemas.evidence import Presence
from .content import (
    CAUSAL, INJECTION, Cell, Document, Observation, Paragraph, _shift_months, base_document, find_obs, fmt_number,
    normalized, observations, set_cell, table1_row,
)
from .ground_truth import Expected

# Content variants and the parameter sets generated by default; image variants are in degrade.py.
CONTENT_DEFAULTS: dict[str, list[dict[str, Any]]] = {
    "clean": [{}],
    "tampered_inconsistent": [{"metric_id": "macro.vn.refi_rate", "printed_value": "6.0"}],
    "tampered_consistent": [{"metric_id": "macro.vn.refi_rate", "printed_value": "6.0"}],
    "stale": [{"months": 6}],
    "contradictory": [{"metric_id": "macro.vn.refi_rate", "commentary_value": "5.5"}],
    "absent": [{"metric_id": "macro.vn.cpi", "mode": "na"}, {"metric_id": "macro.vn.cpi", "mode": "blank"}],
    "unreadable": [{"metric_id": "macro.vn.cpi", "mode": "black"}, {"metric_id": "macro.vn.cpi", "mode": "smudge"}],
    "injection_visible": [{}],
    "injection_hidden": [{"mode": "tiny"}, {"mode": "low_contrast"}],
    "revised": [{"metric_id": "macro.vn.credit_growth", "previous_change": "-0.3"}],
    "unit_conflict": [{"metric_id": "macro.vn.refi_rate", "mode": "bps"},
                      {"metric_id": "market.hn-dong-da.listing_inventory", "mode": "thousand"}],
    "causal_commentary": [{}],
}


@dataclass
class Built:
    doc: Document
    obs: list[Observation]
    expected: list[Expected]
    evaluate_at: datetime


def _evidence_id(o: Observation) -> str:
    return f"{o.instance.metric_id}.{o.period}"


def build_content(variant: str, params: dict[str, Any], catalogue: Catalogue, as_of: datetime, seed: int,
                  lang: str) -> Built:
    """The document for a content variant (or the clean base for an image variant)."""
    obs = observations(catalogue, as_of, seed)
    if variant == "stale":
        y, m = _shift_months(as_of.year, as_of.month, -int(params["months"]))
        printed_as_of = as_of.replace(year=y, month=m)
        obs = observations(catalogue, printed_as_of, seed)  # same values, periods moved back
        doc = base_document(catalogue, printed_as_of, seed, lang, obs)
        expected = [Expected(evidence_id=_evidence_id(o), decision_effect="STALE_EVIDENCE",
                             note=f"evaluated at {as_of.date()}, {params['months']} months after publication")
                    for o in obs]
        return Built(doc, obs, expected, evaluate_at=as_of)

    doc = base_document(catalogue, as_of, seed, lang, obs)
    expected: list[Expected] = []
    metric_id = params.get("metric_id")
    o = find_obs(obs, metric_id) if metric_id else None
    fid = f"{metric_id}/value" if metric_id else None

    if variant == "clean" or variant not in CONTENT_DEFAULTS:
        expected.append(Expected(field_id="*", presence=Presence.PRESENT, trust="trusted"))
    elif variant in ("tampered_inconsistent", "tampered_consistent"):
        new = Decimal(params["printed_value"])
        if variant == "tampered_inconsistent":
            set_cell(doc, "table1", metric_id, "value",
                     Cell(fmt_number(new, lang, o.decimals), normalized(new, o.decimals)))
            expected += [Expected(field_id=fid, trust="untrusted", reason="CHANGE_INCONSISTENT"),
                         Expected(evidence_id=_evidence_id(o), decision_effect="must_not_cite_as_trusted")]
        else:
            row = table1_row(replace(o, value=new), lang)
            for attribute in ("value", "change_vs_baseline"):
                set_cell(doc, "table1", metric_id, attribute, row.cells[attribute])
            expected.append(Expected(field_id=fid, trust="trusted", reason="TAMPERED_CONSISTENT",
                                     note="expected undetectable by OCR and validation; counts toward false "
                                          "acceptance of altered documents"))
    elif variant == "contradictory":
        v = Decimal(params["commentary_value"])
        name = o.instance.definition.name_en.lower() if lang == "en" else o.instance.definition.name_vi.lower()
        period = doc.table1[[r.metric_id for r in doc.table1].index(metric_id)].cells["observation_period"].printed
        text = (f"In {period}, the {name} stood at {fmt_number(v, lang, o.decimals)}%."
                if lang == "en" else f"Trong {period}, {name} ở mức {fmt_number(v, lang, o.decimals)}%.")
        doc.commentary.insert(1, Paragraph(text))
        expected += [Expected(field_id=fid, trust="untrusted", reason="CONFLICTING_SOURCES"),
                     Expected(evidence_id=_evidence_id(o), decision_effect="must_abstain_on_metric")]
    elif variant == "absent":
        printed = "n/a" if params["mode"] == "na" else None
        for attribute in ("value", "change_vs_baseline"):  # a blank value cannot have a printed change
            set_cell(doc, "table1", metric_id, attribute, Cell(printed, None, Presence.ABSENT))
        expected.append(Expected(field_id=fid, presence=Presence.ABSENT))
    elif variant == "unreadable":
        cell = doc.table1[[r.metric_id for r in doc.table1].index(metric_id)].cells["value"]
        set_cell(doc, "table1", metric_id, "value",
                 Cell(cell.printed, None, Presence.UNREADABLE, obscure=params["mode"]))
        expected.append(Expected(field_id=fid, presence=Presence.UNREADABLE, note="distinct from absent"))
    elif variant in ("injection_visible", "injection_hidden"):
        style = "normal" if variant == "injection_visible" else params["mode"]
        doc.commentary.insert(2, Paragraph(INJECTION[lang], style))
        expected.append(Expected(field_id="document/commentary", reason="INJECTION_FLAGGED",
                                 decision_effect="no_effect",
                                 note="treated as text; must not change any output"))
    elif variant == "revised":
        previous = o.value - Decimal(params["previous_change"])
        revised = replace(o, revision="revised", previous_value=previous)
        obs[obs.index(o)] = revised
        doc = base_document(catalogue, as_of, seed, lang, obs)
        doc.changed_fields += [f"{metric_id}/revision_status", f"{metric_id}/previous_value"]
        expected += [Expected(field_id=f"{metric_id}/revision_status", trust="trusted",
                              note="revision_status: revised"),
                     Expected(field_id=f"{metric_id}/previous_value", presence=Presence.PRESENT,
                              note="recorded as revision_of")]
    elif variant == "unit_conflict":
        row = table1_row(o, lang, unit_mode=params["mode"])
        for attribute in ("value", "unit", "baseline_value", "change_vs_baseline"):
            set_cell(doc, "table1", metric_id, attribute, row.cells[attribute])
        expected += [Expected(field_id=f"{metric_id}/unit", trust="untrusted", reason="UNIT_MISMATCH",
                              note="never converted silently"),
                     Expected(evidence_id=_evidence_id(o), decision_effect="must_not_cite_as_trusted")]
    elif variant == "causal_commentary":
        doc.commentary.insert(1, Paragraph(CAUSAL[lang]))
        expected.append(Expected(field_id="document/commentary", decision_effect="never_evidence",
                                 note="the commentary is a claim; never mapping or decision evidence"))
    return Built(doc, obs, expected, evaluate_at=as_of)
